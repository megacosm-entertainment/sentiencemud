unichar_t utf8_toupper(register unichar_t cp)
{
    // ASCII shortcut
    if (cp < 0x80) return UPPER(cp);

    // Iterate until the end of the table OR
    //   it encounters a LOWERCASE codepoint that is smaller than the given codepoint
    for(register int i = 0; _casings[i].lower > 0 && cp <= _casings[i].lower; i++) {
        if (_casings[i].lower == cp)
            return _casings[i].upper;
    }

    return cp;
}

unichar_t utf8_tolower(register unichar_t cp)
{
    // ASCII shortcut
    if (cp < 0x80) return LOWER(cp);

    // Iterate until the end of the table OR
    //   it encounters a UPPERCASE codepoint that is smaller than the given codepoint
    for(register int i = 0; _casings[i].upper > 0 && cp <= _casings[i].upper; i++) {
        if (_casings[i].upper == cp)
            return _casings[i].lower;
    }

    return cp;
}



